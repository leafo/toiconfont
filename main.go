// Command toiconfont builds an icon font from an IcoMoon compatible selection.json file.
package main

import (
	"crypto/sha256"
	"flag"
	"fmt"
	"math"
	"os"
	"path"
	"path/filepath"
	"runtime"
	"runtime/debug"
	"strings"

	"github.com/leafo/toiconfont/selection"
	"github.com/leafo/toiconfont/svgpath"
	"github.com/leafo/toiconfont/ttf"
	"github.com/leafo/toiconfont/woff"
	"github.com/leafo/toiconfont/woff2"
)

// set by the Makefile via -ldflags
var (
	version = ""
	commit  = "head"
	builtAt = "unknown"
)

func versionString() string {
	v := version
	if v == "" {
		v = "dev"
		if info, ok := debug.ReadBuildInfo(); ok && info.Main.Version != "" && info.Main.Version != "(devel)" {
			v = info.Main.Version
		}
	}
	return fmt.Sprintf("toiconfont %s\n  commit: %s\n  built:  %s\n  go:     %s",
		v, commit, builtAt, runtime.Version())
}

func usage() {
	w := flag.CommandLine.Output()
	fmt.Fprint(w, `Usage: toiconfont [options]

Builds an icon font from an IcoMoon compatible selection.json file.

Example:
  toiconfont -in selection.json -woff2 icons.woff2 -woff icons.woff -css icons.css

Options:
`)
	flag.PrintDefaults()
}

// largest distance in font units between a cubic curve and its quadratic
// approximation
const tolerance = 0.25

func glyph(icon selection.Icon, scale, ascent float64) (ttf.Glyph, error) {
	g := ttf.Glyph{Code: icon.Code, Advance: uint16(math.Round(icon.Width * scale))}
	area := 0

	for _, d := range icon.Paths {
		cmds, err := svgpath.Parse(d)
		if err != nil {
			return g, fmt.Errorf("icon %s: %w", icon.Name, err)
		}
		for _, outline := range svgpath.Outline(cmds, tolerance) {
			var contour []ttf.Point
			for _, p := range outline {
				x, y := math.Round(p.X*scale), math.Round(ascent-p.Y*scale)
				if math.Abs(x) > 32767 || math.Abs(y) > 32767 {
					return g, fmt.Errorf("icon %s: coordinate out of range", icon.Name)
				}
				pt := ttf.Point{X: int16(x), Y: int16(y), On: p.On}
				if n := len(contour); n > 0 && pt.On && contour[n-1] == pt {
					continue
				}
				contour = append(contour, pt)
			}
			if n := len(contour); n > 1 && contour[0].On && contour[0] == contour[n-1] {
				contour = contour[:n-1]
			}
			if len(contour) < 3 {
				continue
			}
			for i, p := range contour {
				q := contour[(i+1)%len(contour)]
				area += int(p.X)*int(q.Y) - int(q.X)*int(p.Y)
			}
			g.Contours = append(g.Contours, contour)
		}
	}

	// TrueType outer contours run clockwise
	if area > 0 {
		for _, c := range g.Contours {
			for i, j := 1, len(c)-1; i < j; i, j = i+1, j-1 {
				c[i], c[j] = c[j], c[i]
			}
		}
	}
	return g, nil
}

// src is the value of the @font-face src descriptor
func stylesheet(sel *selection.File, src, display string) string {
	if display != "" {
		display = "\n  font-display: " + display + ";"
	}
	var b strings.Builder
	fmt.Fprintf(&b, `/* generated by toiconfont, do not edit */

@font-face {
  font-family: '%[1]s';
  src: %[2]s;
  font-weight: normal;
  font-style: normal;%[4]s
}

[class^="%[3]s"], [class*=" %[3]s"] {
  /* use !important to prevent issues with browser extensions that change fonts */
  font-family: '%[1]s' !important;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;

  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

`, sel.Family, src, sel.Prefix, display)
	for _, icon := range sel.Icons {
		fmt.Fprintf(&b, ".%s%s:before {\n  content: \"\\%x\";\n}\n", sel.Prefix, icon.Name, icon.Code)
	}
	return b.String()
}

// writeFont returns the stylesheet source for the font it wrote, with a hash
// of the contents appended to the URL
func writeFont(file, url, format string, data []byte) (string, error) {
	if err := os.WriteFile(file, data, 0o644); err != nil {
		return "", err
	}
	fmt.Printf("%s: %d bytes\n", file, len(data))
	if url == "" {
		url = path.Base(filepath.ToSlash(file))
	}
	return fmt.Sprintf("url('%s?%.4x') format('%s')", url, sha256.Sum256(data), format), nil
}

func run() error {
	in := flag.String("in", "selection.json", "IcoMoon compatible selection.json file to read")
	woff2Out := flag.String("woff2", "", "write the WOFF2 font to this file")
	woffOut := flag.String("woff", "", "write the WOFF font to this file")
	ttfOut := flag.String("ttf", "", "write the TrueType font to this file")
	cssOut := flag.String("css", "", "write the stylesheet to this file")
	cssWoff2URL := flag.String("css-woff2-url", "", "WOFF2 URL used in the stylesheet (default: the WOFF2 file name)")
	cssURL := flag.String("css-url", "", "WOFF URL used in the stylesheet (default: the WOFF file name)")
	cssDisplay := flag.String("css-font-display", "", "font-display value used in the stylesheet: auto, block, swap, fallback or optional")
	showVersion := flag.Bool("v", false, "print version")
	flag.Usage = usage
	flag.Parse()

	if *showVersion {
		fmt.Println(versionString())
		return nil
	}
	if flag.NArg() > 0 {
		return fmt.Errorf("unexpected argument %q, see -h", flag.Arg(0))
	}

	if *woff2Out == "" && *woffOut == "" && *ttfOut == "" {
		return fmt.Errorf("nothing to do, pass -woff2, -woff or -ttf")
	}
	if *cssOut != "" && *woff2Out == "" && *woffOut == "" {
		return fmt.Errorf("-css needs -woff2 or -woff")
	}

	switch *cssDisplay {
	case "", "auto", "block", "swap", "fallback", "optional":
	default:
		return fmt.Errorf("invalid -css-font-display %q", *cssDisplay)
	}

	sel, err := selection.Read(*in)
	if err != nil {
		return err
	}

	scale := sel.EmSize / sel.Height
	descent := math.Round(sel.EmSize * sel.Baseline / 100)
	font := ttf.Font{
		Family:     sel.Family,
		UnitsPerEm: uint16(sel.EmSize),
		Ascent:     int16(sel.EmSize - descent),
		Descent:    int16(descent),
	}
	for _, icon := range sel.Icons {
		g, err := glyph(icon, scale, sel.EmSize-descent)
		if err != nil {
			return err
		}
		if len(g.Contours) == 0 {
			return fmt.Errorf("icon %s has no outline", icon.Name)
		}
		font.Glyphs = append(font.Glyphs, g)
	}

	sfnt, tables, err := ttf.Build(font)
	if err != nil {
		return err
	}
	fmt.Printf("%d icons\n", len(sel.Icons))

	var srcs []string
	if *woff2Out != "" {
		data, err := woff2.Encode(tables)
		if err != nil {
			return err
		}
		src, err := writeFont(*woff2Out, *cssWoff2URL, "woff2", data)
		if err != nil {
			return err
		}
		srcs = append(srcs, src)
	}
	if *woffOut != "" {
		data, err := woff.Encode(tables)
		if err != nil {
			return err
		}
		src, err := writeFont(*woffOut, *cssURL, "woff", data)
		if err != nil {
			return err
		}
		srcs = append(srcs, src)
	}
	if *ttfOut != "" {
		if _, err := writeFont(*ttfOut, "", "truetype", sfnt); err != nil {
			return err
		}
	}

	if *cssOut != "" {
		css := stylesheet(sel, strings.Join(srcs, ",\n       "), *cssDisplay)
		if err := os.WriteFile(*cssOut, []byte(css), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "toiconfont:", err)
		os.Exit(1)
	}
}
